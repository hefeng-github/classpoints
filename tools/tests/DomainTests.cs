using ClassPoints.Core;
using ClassPoints.Core.Config;

namespace ClassPoints.Tests;

/// <summary>
/// 这一版的产品规则：周期按序号、班级码随机、班长能管理、配置包能带名单。
/// 这些规则都是"改了会静默出错"的那种，所以每条都钉一个断言。
/// </summary>
internal static class DomainTests
{
    public static void Run(Action<string, bool, string> check)
    {
        void C(string name, bool ok) => check(name, ok, "");
        void C3(string name, bool ok, string detail) => check(name, ok, detail);

        // ---- 周期：按序号，不按学期 ----
        var p1 = new Period { Name = "第 1 周期" };
        var p12 = new Period { Name = "第 12 周期" };
        check("周期名解析出序号", p1.Index == 1 && p12.Index == 12, $"{p1.Index}/{p12.Index}");
        check("周期标题是「第 N 周期」", p12.TitleText == "第 12 周期", p12.TitleText);
        C("人工改过的名字原样显示", new Period { Name = "期中冲刺" }.TitleText == "期中冲刺");
        C("自动生成的旧名字会被识别",
            PeriodNames.LooksAutoGenerated("2026 秋季学期") && !PeriodNames.LooksAutoGenerated("期中冲刺"));

        // ---- 班级码：随机、不带年份、区分大小写去掉易混字 ----
        var code = ClassCodes.New();
        check("班级码是 4-4 形状", code.Length == 9 && code[4] == '-', code);
        check("班级码不含年份", !code.Contains("20", StringComparison.Ordinal), code);
        C3("班级码不含易混字符", !code.Any(c => "IO01".Contains(c)), code);
        var codes = Enumerable.Range(0, 200).Select(_ => ClassCodes.New()).ToHashSet();
        check("班级码基本不重复", codes.Count >= 198, codes.Count.ToString());
        C("老的带年份编号会被换掉",
            ClassCodes.LooksLikeOldScheme("C3-2026") && !ClassCodes.LooksLikeOldScheme(code));

        // ---- 角色：班主任和班长都能管理，班委只能记分 ----
        C("班主任能管理", MemberRole.Owner.CanManage());
        C("班长能管理", MemberRole.CoOwner.CanManage());
        C("班委不能管理", !MemberRole.Officer.CanManage());
        C("班长的显示名是「班长」", MemberRole.CoOwner.ToDisplay() == "班长");
        C("成员身份文案带角色",
            new Member { DisplayName = "李明", Role = MemberRole.CoOwner }.IdentityText == "李明 · 班长");

        // ---- 配置包：名单与管理密码都要能带 ----
        var bundle = new ConfigBundle
        {
            ClassName = "初二（3）班",
            Roster =
            [
                new ConfigStudent { Name = "王小明", SeatNo = 1 },
                new ConfigStudent { Name = "李思远", StudentNo = "07" },
            ],
        };
        bundle.Protect("246810", "135790", "banzhuren2026");

        C("配置包里带了名单", bundle.Roster.Count == 2);
        C("配对口令能取回", bundle.RevealPin("banzhuren2026") == "246810");
        C("管理密码能取回", bundle.RevealAdminPin("banzhuren2026") == "135790");
        C("口令错就取不出", Throws<ConfigException>(() => bundle.RevealAdminPin("wrong-pass")));

        var json = bundle.ToJson();
        var back = ConfigBundle.Parse(json);
        C("名单在 JSON 往返后还在", back.Roster.Count == 2 && back.Roster[0].Name == "王小明");
        C("往返后仍能解出管理密码", back.RevealAdminPin("banzhuren2026") == "135790");

        // 只带管理密码、不带配对口令也要能加密
        var onlyAdmin = new ConfigBundle { ClassName = "X" };
        onlyAdmin.Protect(null, "112233", "passphrase-1");
        C("只预置管理密码也能加密",
            onlyAdmin.RevealAdminPin("passphrase-1") == "112233" && onlyAdmin.RevealPin("passphrase-1") is null);

        C("空姓名会被校验拦住",
            new ConfigBundle { ClassName = "X", Roster = [new ConfigStudent { Name = "  " }] }
                .Validate().Count > 0);
    }

    private static bool Throws<T>(Action action) where T : Exception
    {
        try
        {
            action();
            return false;
        }
        catch (T)
        {
            return true;
        }
        catch (Exception)
        {
            return false;
        }
    }
}
